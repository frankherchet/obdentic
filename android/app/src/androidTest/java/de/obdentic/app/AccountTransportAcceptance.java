package de.obdentic.app;

import static de.obdentic.app.AccountFixtures.require;

import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.InetAddress;
import java.net.Socket;
import java.net.SocketTimeoutException;
import java.nio.charset.StandardCharsets;
import java.security.KeyPairGenerator;
import java.security.KeyStore;
import java.security.cert.Certificate;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.SSLServerSocket;
import javax.net.ssl.TrustManagerFactory;
import org.json.JSONObject;

/**
 * REQ-042.7 and REQ-044.2 for the real HTTPS transport against a local TLS server inside the instrumentation run (a self-signed certificate
 * generated by the Android Keystore, trusted only by the test client). Never OpenAI.
 */
final class AccountTransportAcceptance {
    private static final String ALIAS = "obdentic-test-tls";

    private AccountTransportAcceptance() {}

    private static final class Seen {
        final String path, head, body;

        Seen(String path, String head, String body) {
            this.path = path;
            this.head = head;
            this.body = body;
        }
    }

    static void run() throws Exception {
        KeyStore ks = KeyStore.getInstance("AndroidKeyStore");
        ks.load(null);
        if (ks.containsAlias(ALIAS)) ks.deleteEntry(ALIAS);
        KeyPairGenerator kpg = KeyPairGenerator.getInstance(KeyProperties.KEY_ALGORITHM_EC, "AndroidKeyStore");
        kpg.initialize(new KeyGenParameterSpec.Builder(ALIAS, KeyProperties.PURPOSE_SIGN | KeyProperties.PURPOSE_VERIFY)
            .setAlgorithmParameterSpec(new java.security.spec.ECGenParameterSpec("secp256r1"))
            .setDigests(KeyProperties.DIGEST_NONE, KeyProperties.DIGEST_SHA256, KeyProperties.DIGEST_SHA384, KeyProperties.DIGEST_SHA512)
            .setCertificateSubject(new javax.security.auth.x500.X500Principal("CN=127.0.0.1")).build());
        kpg.generateKeyPair();
        Certificate cert = ks.getCertificate(ALIAS);
        KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        kmf.init(ks, null);
        SSLContext serverContext = SSLContext.getInstance("TLS");
        serverContext.init(kmf.getKeyManagers(), null, null);
        KeyStore trust = KeyStore.getInstance(KeyStore.getDefaultType());
        trust.load(null);
        trust.setCertificateEntry("local", cert);
        TrustManagerFactory tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        tmf.init(trust);
        SSLContext clientContext = SSLContext.getInstance("TLS");
        clientContext.init(null, tmf.getTrustManagers(), null);

        SSLServerSocket server = (SSLServerSocket) serverContext.getServerSocketFactory().createServerSocket(0, 8, InetAddress.getByAddress(new byte[]{127, 0, 0, 1}));
        List<Seen> seen = Collections.synchronizedList(new ArrayList<>());
        Thread accept = new Thread(() -> {
            try {
                while (true) {
                    Socket c = server.accept();
                    Thread t = new Thread(() -> serve(c, seen), "test-tls-connection");
                    t.setDaemon(true);
                    t.start();
                }
            } catch (IOException closed) { /* test ended */ }
        }, "test-tls-server");
        accept.setDaemon(true);
        accept.start();
        try {
            String base = "https://127.0.0.1:" + server.getLocalPort();
            AccountHttp.HttpsTransport transport = new AccountHttp.HttpsTransport(clientContext.getSocketFactory(), (host, session) -> true);

            // a normal POST: form encoded, nothing identifying beyond the app name (REQ-044.2)
            Map<String, String> form = new LinkedHashMap<>();
            form.put("grant_type", "authorization_code");
            form.put("code", "c o d e+&=");
            AccountHttp.Response ok = transport.send(AccountHttp.Request.post(base + "/ok", form, 5000));
            require(ok.ok() && ok.json().optBoolean("ok"), "REQ-042.7 a request reaches the TLS server: " + ok.status);
            Seen s = seen.get(0);
            require(s.head.contains("POST /ok") && s.head.toLowerCase().contains("content-type: application/x-www-form-urlencoded") && s.body.equals("grant_type=authorization_code&code=c%20o%20d%20e%2B%26%3D"), "REQ-042.7 form encoded POST: " + s.body);
            require(s.head.contains("User-Agent: OBDentic") && !s.head.toLowerCase().contains("authorization:") && !s.head.toLowerCase().contains("cookie:") && !s.head.contains("Android") && !s.head.contains("Dalvik"),
                "REQ-044.2 the request carries only the app name as identifier: " + s.head);

            // no redirect is followed
            AccountHttp.Response redirect = transport.send(AccountHttp.Request.get(base + "/redirect", 5000));
            require(redirect.status == 302 && !redirect.ok(), "REQ-042.7 a redirect is returned, not followed: " + redirect.status);
            Thread.sleep(200);
            int landed = 0;
            synchronized (seen) { for (Seen x : seen) if (x.path.equals("/landed")) landed++; }
            require(landed == 0, "REQ-044.2 the redirect target was never requested");

            // read limit of 1 MiB
            AccountHttp.Response big = transport.send(AccountHttp.Request.get(base + "/big", 10000));
            require(big.truncated && big.body.length() <= AccountHttp.LIMIT && !big.ok() && big.json() == null, "REQ-042.7 the response is read up to 1 MiB only: " + big.body.length());

            // error responses
            AccountHttp.Response err = transport.send(AccountHttp.Request.post(base + "/error", form, 5000));
            require(err.status == 400 && err.errorCode().equals("invalid_grant") && !err.ok(), "REQ-042.7 an HTTP error keeps its status and code: " + err.status + " " + err.errorCode());
            AccountHttp.Response nested = transport.send(AccountHttp.Request.get(base + "/error-nested", 5000));
            require(nested.errorCode().equals("token_expired"), "REQ-042.7 nested error code");
            require(new AccountHttp.Response(400, "{\"error\":\"" + "x".repeat(65) + "\"}", false).errorCode().isEmpty() && new AccountHttp.Response(400, "{\"error\":\"a b\"}", false).errorCode().isEmpty()
                && AccountHttp.validCode("a_b.c:d-9"), "REQ-042.7 codes of at most 64 characters from letters, digits and '_.:-'");

            // timeouts
            long t0 = System.nanoTime();
            try { transport.send(AccountHttp.Request.get(base + "/slow", 600)); require(false, "REQ-042.7 the read timeout must fire"); }
            catch (SocketTimeoutException expected) { require((System.nanoTime() - t0) / 1_000_000 < 3000, "REQ-042.7 the read timeout ends the request"); }
            require(AccountHttp.LONG_TIMEOUT_MS == 30_000 && new ChatGptAccount.Config().revokeTimeoutMs == 10_000, "REQ-042.7/REQ-043.11 timeouts of 30 s and 10 s");

            // never plain HTTP, and an untrusted certificate is refused
            try { transport.send(AccountHttp.Request.get("http://127.0.0.1:" + server.getLocalPort() + "/ok", 2000)); require(false, "REQ-044.2 plain HTTP must be refused"); }
            catch (IOException expected) { /* not_https */ }
            try { new AccountHttp.HttpsTransport().send(AccountHttp.Request.get(base + "/ok", 3000)); require(false, "REQ-044.2 an untrusted certificate must be refused"); }
            catch (IOException expected) { /* TLS failure */ }
        } finally {
            server.close();
            ks.deleteEntry(ALIAS);
        }
    }

    private static void serve(Socket socket, List<Seen> seen) {
        try (Socket c = socket) {
            c.setSoTimeout(10000);
            InputStream in = c.getInputStream();
            ByteArrayOutputStream head = new ByteArrayOutputStream();
            int b;
            while ((b = in.read()) >= 0) {
                head.write(b);
                byte[] a = head.toByteArray();
                int n = a.length;
                if (n >= 4 && a[n - 1] == '\n' && a[n - 2] == '\r' && a[n - 3] == '\n' && a[n - 4] == '\r') break;
            }
            String h = head.toString("ISO-8859-1");
            String path = h.split(" ")[1];
            int length = 0;
            for (String line : h.split("\r\n")) if (line.toLowerCase().startsWith("content-length:")) length = Integer.parseInt(line.substring(15).trim());
            byte[] body = new byte[length];
            for (int off = 0; off < length; ) { int r = in.read(body, off, length - off); if (r < 0) break; off += r; }
            seen.add(new Seen(path, h, new String(body, StandardCharsets.UTF_8)));
            OutputStream out = c.getOutputStream();
            switch (path) {
                case "/redirect": reply(out, 302, "Location: /landed\r\n", ""); break;
                case "/big": reply(out, 200, "", new String(new char[2 * AccountHttp.LIMIT]).replace('\0', 'a')); break;
                case "/error": reply(out, 400, "", new JSONObject().put("error", "invalid_grant").put("error_description", "SECRET").toString()); break;
                case "/error-nested": reply(out, 401, "", "{\"error\":{\"code\":\"token_expired\"}}"); break;
                case "/slow": Thread.sleep(3000); reply(out, 200, "", "{}"); break;
                default: reply(out, 200, "", "{\"ok\":true}");
            }
        } catch (Exception ignored) {
            android.util.Log.w("acct-tls", ignored); // the client may hang up (timeout test)
        }
    }

    private static void reply(OutputStream out, int status, String extra, String body) throws IOException {
        byte[] b = body.getBytes(StandardCharsets.UTF_8);
        out.write(("HTTP/1.1 " + status + " X\r\nContent-Type: application/json\r\nContent-Length: " + b.length + "\r\n" + extra + "Connection: close\r\n\r\n").getBytes(StandardCharsets.ISO_8859_1));
        out.write(b);
        out.flush();
    }
}
